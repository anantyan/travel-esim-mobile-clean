import { execSync } from "node:child_process";
import { copyFileSync, existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const rootDir = process.cwd();
const distDir = resolve(rootDir, "dist");
const basePath = process.env.VITE_BASE_PATH || "/travel-esim-mobile-clean/";

console.log(`[build:pages] Building SPA with VITE_BASE_PATH=${basePath}`);

execSync("npx tsc --noEmit && npx vite build", {
  cwd: rootDir,
  stdio: "inherit",
  env: {
    ...process.env,
    VITE_BASE_PATH: basePath,
  },
});

const indexHtmlPath = resolve(distDir, "index.html");
const notFoundHtmlPath = resolve(distDir, "404.html");
const noJekyllPath = resolve(distDir, ".nojekyll");

if (!existsSync(indexHtmlPath)) {
  throw new Error("dist/index.html was not generated by vite build");
}

copyFileSync(indexHtmlPath, notFoundHtmlPath);
writeFileSync(noJekyllPath, "", "utf8");

console.log(
  "[build:pages] Created dist/404.html SPA fallback and dist/.nojekyll",
);
